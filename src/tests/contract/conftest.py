@schemathesis.hook("map_case")
def force_stable_session_id(_, case):
    if case.meta and case.meta.generation.mode is GenerationMode.NEGATIVE:
        return case

    if case.path in {
        "/api/v4/chat/message",
        "/api/v4/chat/message/stream",
    }:
        if isinstance(case.body, dict):
            case.body["session_id"] = "00000000-0000-0000-0000-000000000123"

    if isinstance(case.path_parameters, dict):
        for k in ("file_id", "session_id"):
            if k in case.path_parameters:
                case.path_parameters[k] = "contract-fixed-id"

    return case
