"""Contract tests: the REAL app, generated requests, replayed network.

Why this tree lives apart from ``src/tests/backend``
----------------------------------------------------
25 of the 33 files under ``src/tests/backend`` replace ``sys.modules["azure"]``,
``sys.modules["agent_framework"]`` and friends with ``Mock()`` at import time.
Those stubs are process-global and survive into every module imported after
them, so a test that wants the real code cannot share a pytest session with
them — ``src/tests/backend/conftest.py`` documents the same hazard for the
middleware chain.

The cut here is at the socket, not at the import:

* the FastAPI app is the real one (``app.py`` → ``include_router(app_v4)``);
* the requests are generated by schemathesis from the app's own OpenAPI
  schema — no request is written by hand;
* only outbound HTTP (Foundry / AOAI / Cosmos / AAD) is served from VCR
  cassettes recorded once against real Azure.

Running
-------
Not in ``testpaths``: this is a separate pytest session on purpose.

    # replay (offline, the normal mode — fails if a call has no cassette)
    uv run --project src/backend pytest src/tests/contract -q

    # record (needs the real src/backend/.env + az login)
    uv run --project src/backend pytest src/tests/contract -q \
        --record-mode=once --contract-live
"""

